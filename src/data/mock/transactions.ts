export function getTransactionsByAccount(accountId: string): Transaction[] {
  return transactions.filter((t) => t.accountId === accountId);
}

export function getMonthlyIncome(): number {
  return transactions
    .filter((t) => t.type === "income" && t.status === "cleared" && t.date.startsWith("2026-07"))
    .reduce((sum, t) => sum + t.amountPkr, 0);
}

export function getMonthlyExpenses(): number {
  return transactions
    .filter(
      (t) =>
        (t.type === "expense" || t.type === "loan_payment") &&
        t.status === "cleared" &&
        t.date.startsWith("2026-07")
    )
    .reduce((sum, t) => sum + Math.abs(t.amountPkr), 0);
}
